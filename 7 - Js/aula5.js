// 1. Declaração de variável com LET
// O 'let' permite criar uma variável cujo valor pode ser alterado depois.
// Aqui, criamos o espaço na memória chamado "mensagem" e guardamos um texto (String).
let mensagem = "Olá Impressionador"; 

// 2. Saída de dados
// O console.log é nossa principal ferramenta de visualização para testar se tudo está ok.
console.log(mensagem); 

// 3. Reatribuição de valor
// Note que abaixo usamos 'let' para declarar a variável 'cor' pela primeira vez.
let cor = "vermelho";
console.log(cor); // Saída: vermelho

// Importante: Para mudar o valor, NÃO usamos 'let' novamente. 
// Apenas chamamos o nome da variável e atribuímos o novo valor.
cor = "azul"; 
console.log(cor); // Saída: azul