/**
 * ==========================================
 * TÓPICO: Objetos Globais
 * ==========================================
 * * * O que é um objeto global?
 * Um objeto global é um objeto que está disponível em todo o programa, 
 * independentemente de onde ele é acedido no código.
 * * * Benefícios de utilizar os Objetos Globais:
 * - Disponibilidade Universal
 * - Não Precisam de Importação ou Definição
 * - Controlo de Funções e Dados Comuns
 * * * Por que é que os objetos globais são importantes?
 * - Tornam funções e dados amplamente acessíveis em todo o seu código, 
 * facilitando assim operações comuns.
 * - Isto reduz a necessidade de reinventar essas funcionalidades ou de importar 
 * bibliotecas externas sempre que precisar delas.
 */