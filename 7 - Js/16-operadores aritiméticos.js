// --- OPERADORES ARITMÉTICOS ---
// São usados para realizar operações matemáticas básicas em JavaScript.

// Adição (+): Soma dois valores (X + Y).
let soma = 10 + 5; 

// Subtração (-): Subtrai o valor da direita do valor da esquerda (X - Y).
let sub = 10 - 5; 

// Multiplicação (*): Multiplica dois valores (X * Y).
let multi = 10 * 5; 

// Divisão (/): Divide o primeiro valor pelo segundo (X / Y).
let div = 10 / 5; 

// Módulo (%): Retorna o resto da divisão inteira entre dois números (X % Y).
// Ex: 10 dividido por 3 dá 3 e sobra 1. O resultado aqui será 1.
let resto = 10 % 3; 

// Inversão de sinal (-): Transforma um número positivo em negativo ou vice-versa (-X).
let x = 10;
let inversao = -x; 

// Incremento (++): Adiciona 1 ao valor da variável (X++ ou ++X).
let contador = 5;
contador++; 

// Decremento (--): Subtrai 1 do valor da variável (X-- ou --X).
let decida = 5;
decida--;

// Operadores Aritméticos avançados
//exponenciação **
let base = 2;
let expoente = 3;
let resultado = base ** expoente; // 2 seja elevado a 3
console.log(resultado);